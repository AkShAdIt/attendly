import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

/**
 * Sanitizes cell values to prevent CSV Formula Injection attacks.
 * If a value begins with '=', '+', '-', or '@', it prefixes it with a single quote.
 */
export function sanitizeCsvValue(val: string | number | null | undefined): string {
  if (val === null || val === undefined) return "";
  const str = String(val);
  if (/^[=+\-@\t\r]/.test(str)) {
    return `'${str}`;
  }
  return str;
}

/**
 * Generates and triggers browser download of a sanitized CSV file.
 */
export function downloadCsv(filename: string, headers: string[], rows: (string | number)[][]) {
  const sanitizedHeaders = headers.map(sanitizeCsvValue);
  const sanitizedRows = rows.map((row) => row.map(sanitizeCsvValue));

  const csvContent = [
    sanitizedHeaders.join(","),
    ...sanitizedRows.map((r) =>
      r.map((cell) => `"${String(cell).replace(/"/g, '""')}"`).join(",")
    ),
  ].join("\n");

  const blob = new Blob([csvContent], { type: "text/csv;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.setAttribute("href", url);
  link.setAttribute("download", `${filename}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}

export interface PdfReportOptions {
  title: string;
  institutionName: string;
  metadata: Record<string, string>;
  headers: string[];
  data: (string | number)[][];
  filename: string;
}

/**
 * Generates an official, institutional-grade PDF report using jsPDF and autotable.
 */
export function downloadPdfReport({
  title,
  institutionName,
  metadata,
  headers,
  data,
  filename,
}: PdfReportOptions) {
  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  // Institution Header
  doc.setFontSize(16);
  doc.setFont("helvetica", "bold");
  doc.text(institutionName.toUpperCase(), 14, 18);

  doc.setFontSize(12);
  doc.setFont("helvetica", "normal");
  doc.text(title, 14, 25);

  // Metadata block
  doc.setFontSize(9);
  doc.setTextColor(100);
  let metaY = 32;
  Object.entries(metadata).forEach(([key, val]) => {
    doc.text(`${key}: ${val}`, 14, metaY);
    metaY += 5;
  });

  // Table
  autoTable(doc, {
    startY: metaY + 4,
    head: [headers],
    body: data,
    theme: "striped",
    headStyles: {
      fillColor: [37, 99, 235], // Blue 600
      textColor: [255, 255, 255],
      fontStyle: "bold",
    },
    styles: {
      fontSize: 9,
      cellPadding: 3,
    },
  });

  // Footer Note
  const pageHeight = doc.internal.pageSize.height;
  doc.setFontSize(8);
  doc.setTextColor(150);
  doc.text(
    `Generated by Attendly • ${new Date().toLocaleDateString()} • Verified Institutional Record`,
    14,
    pageHeight - 10
  );

  doc.save(`${filename}.pdf`);
}
